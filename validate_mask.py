"""Local preflight: confirm a PNG has an alpha channel and reports its transparent-pixel ratio.
Run before uploading to Midjourney Editor. Requires Pillow.
Not tested against a live MJ account."""

from PIL import Image
import sys

def check_mask(path: str) -> dict:
    img = Image.open(path)
    if img.mode not in ("RGBA", "LA"):
        return {"ok": False, "reason": f"No alpha channel; mode={img.mode}"}
    alpha = img.split()[-1]  # alpha band
    pixels = img.width * img.height
    transparent = sum(1 for p in alpha.getdata() if p == 0)
    ratio = transparent / pixels
    return {
        "ok": True,
        "mode": img.mode,
        "size": (img.width, img.height),
        "transparent_ratio": round(ratio, 4),
        "note": "Transparent pixels will be regenerated by MJ Editor (V8.X contract assumption)"
    }

if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else "masked.png"
    result = check_mask(path)
    for k, v in result.items():
        print(f"{k}: {v}")